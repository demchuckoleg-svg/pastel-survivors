export const ABILITY_LIST: readonly AbilityDef[] = Object.values(ABILITIES);

export function getAbilityDef(id: AbilityId): AbilityDef {
  return ABILITIES[id];
}

export function getAbilitiesForClass(classId: ClassId): AbilityDef[] {
  return ABILITY_LIST.filter((a) => a.classId === classId);
}

/**
 * Computes the cumulative stats of an ability at a given level (1–10).
 */
export function getAbilityStatsAtLevel(def: AbilityDef, level: number): AbilityStats {
  const clamped = Math.max(1, Math.min(10, Math.floor(level)));
  const stats: AbilityStats = { ...def.baseStats };

  for (const s of def.levels) {
    if (s.level <= clamped) {
      if (s.deltas.damage !== undefined) stats.damage += s.deltas.damage;
      if (s.deltas.cooldown !== undefined) stats.cooldown += s.deltas.cooldown;
      if (s.deltas.count !== undefined) stats.count += s.deltas.count;
      if (s.deltas.area !== undefined) stats.area += s.deltas.area;
      if (s.deltas.pierce !== undefined) stats.pierce += s.deltas.pierce;
      if (s.deltas.duration !== undefined) stats.duration += s.deltas.duration;
      if (s.deltas.speed !== undefined) stats.speed += s.deltas.speed;
      if (s.deltas.knockback !== undefined) {
        stats.knockback = (stats.knockback ?? 0) + s.deltas.knockback;
      }
    }
  }

  stats.damage = Math.max(1, Math.round(stats.damage * 100) / 100);
  stats.cooldown = Math.max(0.15, Math.round(stats.cooldown * 1000) / 1000);
  stats.count = Math.max(1, Math.round(stats.count));
  stats.area = Math.max(4, Math.round(stats.area * 100) / 100);
  stats.pierce = Math.max(0, Math.round(stats.pierce));
  stats.duration = Math.max(0.05, Math.round(stats.duration * 1000) / 1000);
  stats.speed = Math.max(0, Math.round(stats.speed));

  return stats;
}
